function icon(path: string) {
  return function Icon({ size = 16, style, className }: IconProps) {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" style={style} className={className}>
        {path.split("|").map((d, i) => d.startsWith("c") ? <circle key={i} {...parseCircle(d)} /> : d.startsWith("p") ? <polyline key={i} points={d.slice(1)} /> : <path key={i} d={d} />)}
      </svg>
    );
  };
}

function parseCircle(s: string) {
  const [, cx, cy, r] = s.match(/c([\d.]+),([\d.]+),([\d.]+)/) ?? [];
  return { cx, cy, r };
}

